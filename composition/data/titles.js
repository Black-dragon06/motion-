// Title geometry in the feature collages, measured from the reference.
// Each key: [inkLeft, inkRight, baseline, opacity, blur, rotationDeg]
const L = (t) => t;
const lerp = (a, b, t) => a + (b - a) * t;
function track(keys) {
  return (f) => {
    if (f < keys[0][0] || f > keys[keys.length - 1][0]) return null;
    for (let i = 0; i < keys.length - 1; i++) {
      const [fa, a] = keys[i], [fb, b] = keys[i + 1];
      if (f >= fa && f <= fb) { const t = L((f - fa) / (fb - fa || 1)); return a.map((v, j) => lerp(v, b[j], t)); }
    }
    return keys[keys.length - 1][1];
  };
}

