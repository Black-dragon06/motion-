export default function titlesAt(f) {
  const out = {};
  const v = video(f); if (v) out.video = v;
  const m = motion(f); if (m) out.motion = m;
  const c = creation(f);
  if (c) {
    out.creation = c;
    // "Pure" sits above-left of "Creation", proportional to it
    const w = c[1] - c[0];
    out.pure = [c[0] + 0.03 * w, c[0] + 0.28 * w, c[2] - 0.2 * w, c[3], c[4], c[5]];
  }
  return out;
}
